#!/usr/bin/env python3
"""Regenerate COAST_50M in data/coastlines.js: the world coastlines at 1:50m from
Natural Earth, for the briefing's route and SID/STAR charts.

The rest of data/coastlines.js (COAST, the coarse hand-drawn map the space-mission
map uses, and SPACE_SITES) is hand-maintained; this script only rewrites the block
after the GENERATED marker. Coordinates are rounded to 0.01° (~1 km), well below the
1:50m resolution.

Natural Earth is public domain (naturalearthdata.com). Runs rarely:

    python3 scripts/build-coastlines.py
"""
import json, os, urllib.request

ROOT   = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT    = os.path.join(ROOT, "data", "coastlines.js")
SRC    = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_coastline.geojson"
MARKER = "/* ── GENERATED by scripts/build-coastlines.py — do not edit below this line ── */"


def lines():
    """Natural Earth coastline features -> [[lon, lat], ...] polylines."""
    with urllib.request.urlopen(SRC, timeout=60) as r:
        geo = json.load(r)
    out = []
    for f in geo["features"]:
        g = f["geometry"]
        for line in ([g["coordinates"]] if g["type"] == "LineString" else g["coordinates"]):
            out.append([[round(lon, 2), round(lat, 2)] for lon, lat in line])
    return out


def main():
    coast = lines()
    src = open(OUT, encoding="utf-8").read()
    head = src.split(MARKER)[0].rstrip() + "\n\n"
    body = ",\n".join(json.dumps(l, separators=(",", ":")) for l in coast)
    block = (f"{MARKER}\n"
             f"/* World coastlines, Natural Earth 1:50m (public domain): {len(coast)} polylines,\n"
             f"   {sum(map(len, coast))} points, [[lon, lat], ...], not closed. For the briefing charts. */\n"
             f"export const COAST_50M = [\n{body}\n];\n")
    open(OUT, "w", encoding="utf-8").write(head + block)
    print(f"{OUT}: COAST_50M, {len(coast)} polylines, {sum(map(len, coast))} points")


if __name__ == "__main__":
    main()
